@dataclass(frozen=True, slots=True)
class RefFood:
    name: str
    unit: Unit
    kcal: float
    protein: float
    fat: float
    carbs: float
    brand: str | None = None
    portion_label: str | None = None  # для порции: «6 шт», «2 шт»; для штуки — вес «274 г»
    aliases: tuple[str, ...] = field(default=())

    @property
    def title(self) -> str:
        """«Воппер (Burger King)» — название в разборе и в записи."""
        return f"{self.name} ({self.brand})" if self.brand else self.name

    @property
    def nutrients(self) -> Nutrients:
        return Nutrients.of(self.kcal, self.protein, self.fat, self.carbs)

    def scaled(self, quantity: Decimal) -> Nutrients:
        """КБЖУ на количество: граммы для продуктов на 100 г, штуки или порции — для остальных."""
        return self.nutrients.scaled(unit_factor(self.unit, quantity))

    def describe(self) -> str:
        """Строка для модели: «Гречка варёная — на 100 г: 110 ккал, Б 4.2, Ж 1.1, У 21.3»."""
        basis = {Unit.GRAMS: "на 100 г", Unit.PIECE: "на 1 шт"}.get(self.unit, "на порцию")
        weight = f" ({self.portion_label})" if self.portion_label else ""
        return (f"{self.title} — {basis}{weight}: {self.kcal:g} ккал, Б {self.protein:g}, Ж {self.fat:g}, "
                f"У {self.carbs:g}")


def _g(name: str, kcal: float, p: float, f: float, c: float, *aliases: str) -> RefFood:
    return RefFood(name, Unit.GRAMS, kcal, p, f, c, aliases=aliases)


def _pc(name: str, weight: str | None, kcal: float, p: float, f: float, c: float, brand: str | None = None,
        *aliases: str) -> RefFood:
    return RefFood(name, Unit.PIECE, kcal, p, f, c, brand, weight, aliases)


def _por(name: str, label: str, kcal: float, p: float, f: float, c: float, brand: str | None = None,
         *aliases: str) -> RefFood:
    return RefFood(name, Unit.PORTION, kcal, p, f, c, brand, label, aliases)


def _per100(name: str, weight: int, kcal: float, p: float, f: float, c: float, brand: str,
            *aliases: str) -> RefFood:
    """Позиция сети, у которой известны КБЖУ на 100 г и масса: пересчёт на штуку."""
    k = weight / 100
    return _pc(name, f"{weight} г", round(kcal * k, 1), round(p * k, 1), round(f * k, 1), round(c * k, 1), brand,
               *aliases)



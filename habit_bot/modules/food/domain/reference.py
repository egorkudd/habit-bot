REFERENCE: tuple[RefFood, ...] = STAPLES + FAST_FOOD
_WORD = re.compile(r"[a-zа-яё0-9%&']+")


def _fold(text: str) -> str:
    return text.casefold().replace("ё", "е").strip()


def _stem(word: str) -> str:
    """Грубая основа русского слова для поиска: «гречки» и «гречку» → «греч»."""
    return word[:5] if len(word) > 5 else word.rstrip("аяоеиыуюьй") or word


def _keys(food: RefFood) -> set[str]:
    brand = f"{food.brand} {BRAND_WORDS[food.brand]}" if food.brand else ""
    words = _WORD.findall(_fold(" ".join([food.name, brand, *food.aliases])))
    return {_stem(w) for w in words if len(w) >= 3}


_INDEX: tuple[tuple[RefFood, set[str]], ...] = tuple((f, _keys(f)) for f in REFERENCE)


def search(text: str, limit: int = SEARCH_LIMIT) -> list[RefFood]:
    """Позиции, в названии, бренде или синонимах которых есть слова из текста; больше совпадений — выше."""
    words = {_stem(w) for w in _WORD.findall(_fold(text)) if len(w) >= 3}
    scored = [(len(keys & words), i, f) for i, (f, keys) in enumerate(_INDEX) if keys & words]
    scored.sort(key=lambda s: (-s[0], s[1]))
    return [f for _, _, f in scored[:limit]]


def find(name: str, foods: Iterable[RefFood] = REFERENCE) -> RefFood | None:
    """Позиция по названию из ответа модели или импорта: «Воппер (Burger King)», «Гречка варёная» или синоним
    («гречка»). Одинаковые названия у разных сетей («Чизбургер») без бренда не выбираются."""
    wanted = _fold(name)
    exact = [f for f in foods if _fold(f.title) == wanted]
    if exact:
        return exact[0]
    named = [f for f in foods if _fold(f.name) == wanted or wanted in (_fold(a) for a in f.aliases)]
    return named[0] if len(named) == 1 else None
